#!/usr/bin/env python3
"""Writes port/common/byte_order_fields.h: a structured binding for each field count.

C++20 has no structured binding of a variable count (that is C++26's P1061), so
``bind_fields<count>`` needs one ``auto& [f1, ..., fN] = record;`` per count. This script writes
them, up to ``MAX_FIELDS``; ``test_gen_byte_order_fields.py`` checks that the committed header is
what it writes.

    python port/tools/gen_byte_order_fields.py            # rewrites the header
"""

from pathlib import Path

MAX_FIELDS = 40
COLUMNS = 100
HEADER = Path(__file__).resolve().parents[1] / "common" / "byte_order_fields.h"


def wrapped(items, first, indent, last):
    """``first`` + the comma-separated ``items`` + ``last``, in lines of at most COLUMNS."""
    lines = []
    line = first
    for i, item in enumerate(items):
        piece = item + ("," if i + 1 < len(items) else last)
        candidate = line + ("" if line in (first, indent) else " ") + piece
        if len(candidate) > COLUMNS:
            lines.append(line.rstrip())
            line = indent + piece
        else:
            line = candidate
    lines.append(line)
    return lines


def render():
    """The header's text."""
    out = [
        "// Generated by port/tools/gen_byte_order_fields.py. Do not edit.",
        "//",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Copyright (c) 2026 the OpenRAC contributors",
        "//",
        "// bind_fields<count>(record, fn) calls fn on each of the `count` fields of the aggregate",
        "// `record`, in declaration order, through a structured binding of that count. C++20 has no",
        "// structured binding of a variable count (that is C++26's P1061), so every count up to",
        "// kMaxFields has a case of its own here. common/byte_order.h counts a record's fields and",
        "// calls this; nothing else does.",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace openrac::byte_order {",
        "",
        "// The most fields a record may have: the structured bindings below go that far.",
        f"inline constexpr std::size_t kMaxFields = {MAX_FIELDS};",
        "",
        "// fn, called on each field of the aggregate `record` of `count` fields, in declaration order.",
        "template <std::size_t count, typename T, typename Fn>",
        "void bind_fields(T& record, Fn&& fn) {",
        '    static_assert(count <= kMaxFields, "a record with more fields than bind_fields binds");',
        "    if constexpr (count == 0) {",
        "        // Nothing to bind; the parameters are used by the other cases.",
        "        static_cast<void>(record);",
        "        static_cast<void>(fn);",
    ]
    for n in range(1, MAX_FIELDS + 1):
        names = [f"f{i}" for i in range(1, n + 1)]
        out.append(f"    }} else if constexpr (count == {n}) {{")
        out.extend(wrapped(names, "        auto& [", "               ", "] = record;"))
        out.extend(wrapped([f"fn({name})" for name in names], "        ", "        ", ";"))
    out.extend(["    }", "}", "", "}  // namespace openrac::byte_order", ""])
    return "\n".join(out)


def main():
    HEADER.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {HEADER}")


if __name__ == "__main__":
    main()
